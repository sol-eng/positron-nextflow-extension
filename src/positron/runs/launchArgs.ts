// Builds the `nextflow run` command line and the generated config for a run.
// Kept free of `vscode` so it can be unit tested.

import * as path from "path";
import * as semver from "semver";

export type LaunchConfig = {
  /** absolute path of the entry script */
  script: string;
  /** launch directory */
  cwd: string;
  profiles: string[];
  paramsFile?: string;
  params: [string, string][];
  /** session to resume */
  resumeSessionId?: string;
  /** Workbench settings that override the pipeline's own */
  workbench?: { cluster?: string; resourceProfile?: string };
  extraArgs: string[];
};

export type RunFiles = {
  dir: string;
  record: string;
  output: string;
  log: string;
  config: string;
  events: string;
  trace: string;
  report: string;
  timeline: string;
  dag: string;
};

export function runFiles(cwd: string, runName: string): RunFiles {
  const dir = path.join(cwd, ".nextflow", "positron", runName);
  const file = (name: string) => path.join(dir, name);
  return {
    dir,
    record: file("run.json"),
    output: file("output.log"),
    log: file("nextflow.log"),
    config: file("positron.config"),
    events: file("events.ndjson"),
    trace: file("trace.txt"),
    report: file("report.html"),
    timeline: file("timeline.html"),
    dag: file("dag.html")
  };
}

/**
 * A run name Nextflow accepts (lowercase, starting with a letter, at most 80
 * characters) that also names the run's directory.
 */
export function makeRunName(script: string, now: Date, suffix = ""): string {
  const base =
    path
      .basename(script, ".nf")
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^[^a-z]+|-+$/g, "") || "run";
  const pad = (n: number) => String(n).padStart(2, "0");
  const stamp =
    `${now.getFullYear()}${pad(now.getMonth() + 1)}${pad(now.getDate())}` +
    `-${pad(now.getHours())}${pad(now.getMinutes())}${pad(now.getSeconds())}`;
  return `${base.slice(0, 50)}-${stamp}${suffix ? `-${suffix}` : ""}`;
}

/**
 * `-plugins` replaces the pipeline's own plugin list rather than adding to
 * it, so the events plugin is appended to the declared plugins.
 */
export function mergePlugins(declared: string[], eventsPlugin: string) {
  const id = eventsPlugin.split("@")[0];
  if (declared.some((p) => p.split("@")[0] === id)) return declared;
  return [...declared, eventsPlugin];
}

export function buildRunArgs(
  config: LaunchConfig,
  files: RunFiles,
  runName: string,
  plugins: string[]
): string[] {
  const args = [
    "-log",
    files.log,
    "run",
    config.script,
    "-name",
    runName,
    "-ansi-log",
    "false",
    "-c",
    files.config,
    "-with-trace",
    files.trace,
    "-with-report",
    files.report,
    "-with-timeline",
    files.timeline,
    "-with-dag",
    files.dag
  ];
  if (config.profiles.length) args.push("-profile", config.profiles.join(","));
  if (config.paramsFile) args.push("-params-file", config.paramsFile);
  for (const [key, value] of config.params) args.push(`--${key}`, value);
  if (config.resumeSessionId) args.push("-resume", config.resumeSessionId);
  if (plugins.length) args.push("-plugins", plugins.join(","));
  args.push(...config.extraArgs);
  return args;
}

/** The config passed with `-c`, which wins over the pipeline's own config. */
export function buildRunConfig(
  config: LaunchConfig,
  files: RunFiles,
  withEvents: boolean
): string {
  const workbench: string[] = [];
  if (withEvents) workbench.push(`eventsFile = ${groovyString(files.events)}`);
  if (config.workbench?.cluster)
    workbench.push(`cluster = ${groovyString(config.workbench.cluster)}`);
  if (config.workbench?.resourceProfile)
    workbench.push(
      `resourceProfile = ${groovyString(config.workbench.resourceProfile)}`
    );
  const lines = [
    "// Generated by the Positron Nextflow extension for this run.",
    "trace.overwrite = true",
    "report.overwrite = true",
    "timeline.overwrite = true",
    "dag.overwrite = true"
  ];
  if (workbench.length) {
    lines.push("workbench {", ...workbench.map((l) => `    ${l}`), "}");
  }
  return lines.join("\n") + "\n";
}

export function groovyString(value: string): string {
  return `'${value.replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;
}

/**
 * Parse `--key value --flag` style input into params. A flag without a value
 * becomes `true`, as on the Nextflow command line.
 */
export function parseParams(input: string): [string, string][] {
  const tokens = [...input.matchAll(/"([^"]*)"|'([^']*)'|(\S+)/g)].map(
    (m) => m[1] ?? m[2] ?? m[3]
  );
  const params: [string, string][] = [];
  for (let i = 0; i < tokens.length; i++) {
    const token = tokens[i];
    if (!token.startsWith("--")) continue;
    const [key, inline] = token.slice(2).split(/=(.*)/s);
    if (inline !== undefined) {
      params.push([key, inline]);
    } else if (i + 1 < tokens.length && !tokens[i + 1].startsWith("--")) {
      params.push([key, tokens[++i]]);
    } else {
      params.push([key, "true"]);
    }
  }
  return params;
}

export function formatParams(params: [string, string][]): string {
  return params
    .map(([k, v]) => `--${k} ${/\s/.test(v) ? `"${v}"` : v}`)
    .join(" ");
}

/** Parse `nextflow -version` output, e.g. `version 26.10.3 build 14229`. */
export function parseNextflowVersion(output: string): string | undefined {
  return output.match(/version\s+(\d+\.\d+\.\d+)/)?.[1];
}

/** Does `ps -o command=` output belong to the Nextflow run `runName`? */
export function isNextflowRun(command: string, runName: string): boolean {
  return /nextflow/i.test(command) && command.includes(runName);
}

/** Quote a word for bash. */
export function shellQuote(word: string): string {
  return /^[\w@%+=:,./-]+$/.test(word)
    ? word
    : `'${word.replace(/'/g, `'\\''`)}'`;
}

export type DriverScript = {
  nextflow: string;
  args: string[];
  cwd: string;
  output: string;
  /** the session user's home, which the job shares */
  home: string;
  user: string;
  /** Nextflow's home, with its plugins and framework */
  nxfHome: string;
  /** JVM heap for the driver, in MB */
  xmxMb: number;
  javaHome?: string;
};

/**
 * The script a driver job runs. `exec` makes the JVM the job's main process,
 * so stopping the job sends SIGTERM to Nextflow, which then cancels its tasks.
 * The job's own Workbench credentials are inherited as is.
 *
 * Workbench job containers run as the user's uid, which may have no passwd
 * entry there, so HOME can be unset or `/` (Nextflow then fails to create
 * `//.nextflow`). HOME, USER, LOGNAME and NXF_HOME are set from the session,
 * as the nf-workbench plugin does for task jobs, and `~/.local/bin` comes
 * first on the PATH so the plugin finds the launcher installed there.
 */
export function buildDriverScript(script: DriverScript): string {
  const lines = [
    "#!/bin/bash",
    "# Generated by the Positron Nextflow extension: the Nextflow driver for this run.",
    "set -e",
    `cd ${shellQuote(script.cwd)}`,
    `export HOME=${shellQuote(script.home)} USER=${shellQuote(script.user)} LOGNAME=${shellQuote(script.user)}`,
    `export NXF_HOME=${shellQuote(script.nxfHome)}`,
    // a job's PATH comes from its image; fall back to the usual directories
    `export PATH=${shellQuote(`${script.home}/.local/bin`)}:"\${PATH:-/usr/local/bin:/usr/bin:/bin}"`,
    `export NXF_OPTS=${shellQuote(`-Xms512m -Xmx${script.xmxMb}m`)}`
  ];
  if (script.javaHome)
    lines.push(`export JAVA_HOME=${shellQuote(script.javaHome)}`);
  lines.push(
    `exec ${[script.nextflow, ...script.args].map(shellQuote).join(" ")} >>${shellQuote(script.output)} 2>&1`
  );
  return lines.join("\n") + "\n";
}

export type { JobState } from "./workbenchApi";

export type DriverMode = "local" | "job";

/**
 * Where the driver runs: `auto` uses a Workbench job when one is possible,
 * `job` insists on one, and `local` never uses one.
 */
export function resolveDriverMode(
  setting: string,
  jobAvailable: boolean
): { mode: DriverMode; ask: boolean } {
  if (setting === "local" || !jobAvailable)
    return { mode: "local", ask: false };
  return { mode: "job", ask: setting !== "job" };
}

/** Job ids of tasks a run never reported as finished, to cancel them. */
export function orphanedJobIds(
  tasks: { status: string; nativeId?: string }[]
): string[] {
  const done = new Set(["COMPLETED", "FAILED", "ABORTED", "CACHED"]);
  return tasks
    .filter((t) => t.nativeId && !done.has(t.status))
    .map((t) => t.nativeId!);
}

/** The oldest nf-workbench that writes run events (`workbench.eventsFile`). */
export const MIN_EVENTS_PLUGIN = "0.2.0";

/**
 * The events plugin to load, from the `nextflow.run.eventsPlugin` setting and
 * the plugin directories Nextflow has installed (`<id>-<version>`). A setting
 * with a version (`nf-workbench@0.3.0`) must be installed exactly; without one
 * (`nf-workbench`) the newest installed version from MIN_EVENTS_PLUGIN on is
 * used. Undefined if none is installed.
 */
export function pickEventsPlugin(
  setting: string,
  installed: string[]
): string | undefined {
  const [id, pinned] = setting.split("@");
  if (pinned)
    return installed.includes(`${id}-${pinned}`) ? setting : undefined;
  const versions = installed
    .filter((name) => name.startsWith(`${id}-`))
    .map((name) => name.slice(id.length + 1))
    .filter((v) => semver.valid(v) && semver.gte(v, MIN_EVENTS_PLUGIN))
    .sort(semver.rcompare);
  return versions.length ? `${id}@${versions[0]}` : undefined;
}
